namespace paintbrush {

/* One recorded Play Pad control sample (x/y/energy/hold over time). */
struct StageSample
{
    float x = 0.5f;
    float y = 0.5f;
    float energy = 0.0f;
    bool hold = false;
    qint64 tMs = 0;
};

/* Deterministic, loopable Play Pad control envelope stored on a stage layer.
 * At t=0 and t=period it evaluates NEUTRAL so the static/rest frame contract
 * is preserved; inside the loop it drives modulation, parallax and lighting. */
struct StageEnvelope
{
    QVector<StageSample> samples;
    qint64 periodMs = 3000;

    bool isValid() const { return samples.size() >= 2 && periodMs > 0; }
    QByteArray serialize() const;
    static StageEnvelope deserialize(const QByteArray &data);
    static StageEnvelope fromSamples(const QVector<StageSample> &samples,
                                     qint64 periodMs);
    StageSample sampleAt(qint64 timeMs) const;
};

/* Stage layer metadata keys / values (plain strings so CanvasLayer checks do
 * not need this header). */
namespace stagekeys {
inline QString living() { return QStringLiteral("stage.living"); }
inline QString scene() { return QStringLiteral("stage.scene"); }
inline QString role() { return QStringLiteral("stage.role"); }
inline QString depth() { return QStringLiteral("stage.depth"); }
inline QString parallax() { return QStringLiteral("stage.parallax"); }
inline QString lightPulse() { return QStringLiteral("stage.lightPulse"); }
inline QString autoMotion() { return QStringLiteral("stage.auto"); }
inline QString envelope() { return QStringLiteral("stage.envelope"); }
inline QString motionClip() { return QStringLiteral("stage.motionClip"); }
inline QString loopPeriodMs() { return QStringLiteral("stage.loopPeriodMs"); }
} // namespace stagekeys

struct StageRuntime
{
    /* The canonical deterministic stage/Living loop. */
    static constexpr qint64 kLoopPeriodMs = 3000;

    /* A layer whose motion is derived from its own committed raster (Photo
     * Regime H creative subject, Rigged Stage subject). */
    static bool isDerivedLiving(const CanvasLayer &layer);
    /* A stage member whose parallax/light pulse depends on canonical time. */
    static bool isStageAnimated(const CanvasLayer &layer);

    /* Decode the clip stored in `stage.motionClip` (no rig needed). */
    static motion::PuppetMotionClip storedClip(const CanvasLayer &layer);
    static QByteArray encodeClip(const motion::PuppetMotionClip &clip);

    /* Derived rig built ONCE from the layer raster (+ optional mask), cached
     * by content; capped for interactive preview and upscaled back to the
     * layer raster size so placement is unchanged. */
    static motion::PuppetRig rigForLayer(const CanvasLayer &layer);

    /* Render the derived living frame at canonical time. Returns an empty
     * image when the layer has no valid rig (caller then keeps the raster). */
    static QImage renderDerivedFrame(const CanvasLayer &layer, qint64 timeMs);

    static StageEnvelope envelopeForLayer(const CanvasLayer &layer);
    static motion::PuppetMotionClip clipForLayer(const CanvasLayer &layer,
                                                 const motion::PuppetRig &rig);

    /* Effective amplitude at timeMs: the layer's typed PuppetEffect
     * amplitude modulated by the recorded envelope (or deterministic idle
     * automation). Neutral at the loop boundary. */
    static motion::PuppetEffect effectAtTime(const CanvasLayer &layer,
                                             qint64 timeMs);

    /* Canvas-space parallax offset for a stage prop (0 for the subject and at
     * the t=0/loop boundary). Deterministic from metadata + envelope. */
    static QPointF parallaxOffset(const CanvasLayer &layer, const QSize &canvas,
                                  qint64 timeMs);
    /* Multiplicative lighting gain from `stage.lightPulse` (1 at boundary). */
    static float lightGain(const CanvasLayer &layer, qint64 timeMs);

    /* Attach the stage metadata block to one layer. `envelope` is the
     * serialized StageEnvelope (may be empty -> deterministic automation). */
    static void applyStageMetadata(CanvasLayer *layer, const QString &scene,
                                   const QString &role, float depth,
                                   float parallax, float lightPulse,
                                   const QByteArray &envelope);
    static void clearLivingMetadata(CanvasLayer *layer);

    /* Real Powder prop: build the deterministic GlitterPowder state and its
     * 1x raster with the existing powder engine. The committed layer keeps
     * materialPreset/materialState so export re-renders at full scale. */
    static QImage renderPowderField(const QSize &stageSize, quint32 seed,
                                    const QColor &color, QByteArray *stateOut);
};

/* Typed undo for attaching/detaching a derived living effect (and clearing
 * the metadata that selects it). SetPuppetCommand cannot express the derived
 * metadata half, so this command keeps a full before/after pair. Raster data
 * is never captured or modified. */
class SetStageLivingCommand : public UndoCommand
{
public:
    int layerId = 0;
    int beforeAssetId = -1;
    motion::PuppetEffect beforeEffect;
    QVariantMap beforeMetadata;
    int afterAssetId = -1;
    motion::PuppetEffect afterEffect;
    QVariantMap afterMetadata;
    QString desc;

    Kind kind() const override { return Kind::SetPuppet; }
    QString description() const override { return desc; }
    void apply(PaintbrushDocument &doc) override;
    void revert(PaintbrushDocument &doc) override;
};

} // namespace paintbrush

#endif // PB_STAGE_HPP
