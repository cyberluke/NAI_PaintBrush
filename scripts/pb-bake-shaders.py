#!/usr/bin/env python3
"""Bake the Paintbrush GPU Art Runtime shaders with qsb and emit a C++ header.

Qt 6.10+ removed QShader::fromSourceString, so every QSG material must return
a QShader built from a qsb-baked pack. This script runs `qsb` on each
shaders/*.vert|frag pair, embeds the binary .qsb bytes as C arrays in
`art/gpu/shaders_qsb.h` and prints the loader map used by pb_gpu_materials.cpp.

usage: python scripts/pb-bake-shaders.py [--check]
"""
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SHADER_DIR = os.path.join(ROOT, "modules", "gui", "qt", "paintbrush", "art", "gpu", "shaders")
OUT_H = os.path.join(ROOT, "modules", "gui", "qt", "paintbrush", "art", "gpu", "shaders_qsb.h")
QSB = os.environ.get("QSB", "qsb.exe")
TMP = os.path.join(ROOT, "build", "pb_qsb_tmp")

# name -> (vertex source, fragment source)
SHADERS = {
    "paper": ("paper.vert", "paper.frag"),
    "glitter": ("glitter.vert", "glitter.frag"),
    "finish": ("finish.vert", "finish.frag"),
    "powder": ("powder.vert", "powder.frag"),
}

# Explicit targets: the shaders use uint bit-twiddling (exact ports of the
# CPU art_noise hashing), so GLSL 100es/120 cannot be used — only versions
# with uint (300es/330/150). HLSL 50 / MSL 12 cover the other RHI backends.
QSB_FLAGS = ["--glsl", "300 es,330,150", "--hlsl", "50", "--msl", "12", "-o"]


def bake(name, vert, frag):
    os.makedirs(TMP, exist_ok=True)
    v = os.path.join(SHADER_DIR, vert)
    f = os.path.join(SHADER_DIR, frag)
    # one .qsb per stage: Qt's QShader represents a single stage, and
    # fromSerialized() on a combined vert+frag pack loses the stage split.
    out_v = os.path.join(TMP, name + "_v.qsb")
    out_f = os.path.join(TMP, name + "_f.qsb")
    if subprocess.call([QSB] + QSB_FLAGS + [out_v, v]) != 0:
        raise SystemExit("qsb failed for " + vert)
    if subprocess.call([QSB] + QSB_FLAGS + [out_f, f]) != 0:
        raise SystemExit("qsb failed for " + frag)
    with open(out_v, "rb") as fh:
        vdata = fh.read()
    with open(out_f, "rb") as fh:
        fdata = fh.read()
    return vdata, fdata


def c_array(name, data):
    lines = ["static const unsigned char kQSB_%s[] = {" % name]
    for i in range(0, len(data), 16):
        chunk = data[i:i + 16]
        lines.append("    " + ", ".join("0x%02x" % b for b in chunk) + ",")
    lines.append("};")
    return "\n".join(lines)


def main():
    check = "--check" in sys.argv
    entries = {}
    for name, (vert, frag) in SHADERS.items():
        vdata, fdata = bake(name, vert, frag)
        entries[name + "_v"] = len(vdata)
        entries[name + "_f"] = len(fdata)

    parts = [
        "/* GENERATED by scripts/pb-bake-shaders.py — do not edit. */",
        "/* qsb-baked NAI Paintbrush GPU Art Runtime shader packs (one per",
        " * stage: a combined pack would lose the vertex/fragment split). */",
        "#ifndef PB_ART_GPU_SHADERS_QSB_H",
        "#define PB_ART_GPU_SHADERS_QSB_H",
        "",
    ]
    for name in SHADERS:
        with open(os.path.join(TMP, name + "_v.qsb"), "rb") as fh:
            parts.append(c_array(name.upper() + "_VERT", fh.read()))
        parts.append("")
        with open(os.path.join(TMP, name + "_f.qsb"), "rb") as fh:
            parts.append(c_array(name.upper() + "_FRAG", fh.read()))
        parts.append("")
    parts.append("#endif // PB_ART_GPU_SHADERS_QSB_H")
    text = "\n".join(parts) + "\n"

    if check:
        print("would write shaders_qsb.h with:", ", ".join(
            "%s=%dB" % (k, v) for k, v in entries.items()))
        return 0

    with open(OUT_H, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote", OUT_H, "with", ", ".join(
        "%s=%dB" % (k, v) for k, v in entries.items()))
    return 0


if __name__ == "__main__":
    sys.exit(main())